ORDER = ["biome", "ecoregion", "country", "temperature", "elevation", "population", "housing"]
LABEL = {"biome": "Biome (acc)", "ecoregion": "EcoRegion (acc)", "country": "Country (acc)",
         "temperature": "Temperature (R²)", "elevation": "Elevation (R²)",
         "population": "Population (R²)", "housing": "California housing (R²)"}
PAPER = {"tte": [77.8, 67.4, 94.8, .946, .839, .790, .532], "satclip_l40": [68.9, 69.3, 82.8, .825, .666, .684, .400]}
# reference categorical palette (dataviz skill), fixed order, light mode
COL = {"tte": "#2a78d6", "satclip_l40": "#eb6834", "coords": "#1baf7a", "satclip_l10": "#eda100", "sh_l10": "#e87ba4"}
NAME = {"tte": "TTE", "satclip_l40": "SatCLIP L40", "coords": "kNN on raw coordinates", "satclip_l10": "SatCLIP L10",
        "sh_l10": "Spherical harmonics L10 (no learning)", "xyz": "raw xyz"}
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"
N_BOOT = 1000


def fmt(task, v):
    return f"{100*v:.1f}" if TASKS[task] == "cls" else f"{v:.3f}"


def wscore(task, y, p, w):
    if TASKS[task] == "cls":
        return np.sum(w * (p == y)) / w.sum()
    yb = np.sum(w * y) / w.sum()
    return 1 - np.sum(w * (y - p) ** 2) / np.sum(w * (y - yb) ** 2)


def boot_gap(task, tag, a="tte", b="satclip_l40", by_block=True, seed=0, probe="ridge", probe_b=None):
    za = np.load(PTS / f"{task}__{a}__{probe}__{tag}.npz")
    zb = np.load(PTS / f"{task}__{b}__{probe_b or probe}__{tag}.npz")
    y = za["y"]
    m = za["fold"] >= 0
    y, pa, pb = y[m], za["pred"][m], zb["pred"][m]
    g = za["groups"][m] if by_block else np.arange(m.sum())
    ug, inv = np.unique(g, return_inverse=True)
    rng = np.random.default_rng(seed)
    point = wscore(task, y, pa, np.ones_like(y, float)) - wscore(task, y, pb, np.ones_like(y, float))
    d = []
    for _ in range(N_BOOT):
        w = np.bincount(rng.integers(0, len(ug), len(ug)), minlength=len(ug))[inv].astype(float)
        d.append(wscore(task, y, pa, w) - wscore(task, y, pb, w))
    lo, hi = np.percentile(d, [2.5, 97.5])
    return point, lo, hi


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=8)
    ax.grid(True, color=GRID, lw=0.6)
    ax.set_axisbelow(True)


from analyze_e3 import e3_sections, e2_sections  # noqa: E402  (helpers passed in to avoid a circular import)


def main():
    e0 = pd.concat([pd.read_csv(OUT / "results_e0_random.csv").query("task != 'population'"),
                    pd.read_csv(OUT / "results_e0_pop.csv")])
    e1 = pd.read_csv(OUT / "results_e1_block.csv")
    sparse = pd.read_csv(OUT / "results_e1b_sparse.csv") if (OUT / "results_e1b_sparse.csv").exists() else None
    md = ["# Results tables (generated by src/analyze.py)\n"]

    # ---------------- E0
    t = e0.groupby(["task", "encoder"]).score.agg(["mean", "std"]).reset_index()
    md.append("## E0: random 80/20 split, mean ± sd over seeds 42–46 (rebuilt labels)\n")
    md.append("| encoder | " + " | ".join(LABEL[k] for k in ORDER) + " |")
    md.append("|---|" + "---|" * len(ORDER))
    for enc in ["tte", "satclip_l40", "satclip_l10", "sh_l10", "xyz", "coords"]:
        cells = []
        for k in ORDER:
            r = t[(t.task == k) & (t.encoder == enc)]
            cells.append(f"{fmt(k, r['mean'].iloc[0])} ± {fmt(k, r['std'].iloc[0])}" if len(r) else "")
        md.append(f"| {NAME[enc]} | " + " | ".join(cells) + " |")
    for enc in ["tte", "satclip_l40"]:
        md.append(f"| paper Table 1: {NAME[enc]} | " + " | ".join(str(v) for v in PAPER[enc]) + " |")
    md.append("")

    # ---------------- E1 summary per block size
    g = e1.groupby(["task", "encoder", "split_size_km"]).agg(
        score=("score", "mean"), sd=("score", "std"), nn=("median_nn_km", "mean"),
        ceiling=("ceiling", "mean"), acc_sup=("acc_supported", "mean")).reset_index()
    rnd = e0.groupby(["task", "encoder"]).agg(score=("score", "mean"), nn=("median_nn_km", "mean")).reset_index()
    md.append("## E1: spatial-block 5-fold CV, mean over 5 grid offsets (sd in parentheses)\n")
    for k in ORDER:
        sizes = sorted(g[g.task == k].split_size_km.unique())
        md.append(f"### {LABEL[k]}\n")
        nn_row = [f"{rnd[(rnd.task == k) & (rnd.encoder == 'tte')].nn.iloc[0]:.0f}"] + \
                 [f"{g[(g.task == k) & (g.encoder == 'tte') & (g.split_size_km == s)].nn.iloc[0]:.0f}" for s in sizes]
        md.append("| | random | " + " | ".join(f"{int(s)} km" for s in sizes) + " |")
        md.append("|---|---|" + "---|" * len(sizes))
        md.append("| median km to nearest label | " + " | ".join(nn_row) + " |")
        for enc in ["tte", "satclip_l40", "satclip_l10", "sh_l10", "coords"]:
            r0 = rnd[(rnd.task == k) & (rnd.encoder == enc)]
            cells = [fmt(k, r0.score.iloc[0])]
            for s in sizes:
                r = g[(g.task == k) & (g.encoder == enc) & (g.split_size_km == s)]
                cells.append(f"{fmt(k, r.score.iloc[0])} ({fmt(k, r.sd.iloc[0])})")
            md.append(f"| {NAME[enc]} | " + " | ".join(cells) + " |")
        if TASKS[k] == "cls":
            r = g[(g.task == k) & (g.encoder == "tte")]
            md.append("| share of test points whose class is in training (ceiling) | 100 | " + " | ".join(f"{100*c:.1f}" for c in r.ceiling) + " |")
            for enc in ["tte", "satclip_l40"]:
                r = g[(g.task == k) & (g.encoder == enc)]
                md.append(f"| {NAME[enc]}: accuracy on supported points | | " + " | ".join(f"{100*c:.1f}" for c in r.acc_sup) + " |")
        md.append("")

    # ---------------- gap TTE - SatCLIP L40 with block-bootstrap CI, and offset consistency
    md.append("## TTE minus SatCLIP L40, with 95% block-bootstrap CI (offset 0) and sign consistency across 5 offsets\n")
    md.append("| task | split | gap | 95% CI | offsets where TTE ahead |")
    md.append("|---|---|---|---|---|")
    gap_rows = []
    for k in ORDER:
        p, lo, hi = boot_gap(k, "kindrandom_seed42", by_block=False)
        md.append(f"| {LABEL[k]} | random (seed 42) | {fmt(k, p)} | [{fmt(k, lo)}, {fmt(k, hi)}] | |")
        gap_rows.append(dict(task=k, size=0, gap=p, lo=lo, hi=hi, nn=rnd[(rnd.task == k) & (rnd.encoder == 'tte')].nn.iloc[0]))
        for s in sorted(e1[e1.task == k].split_size_km.unique()):
            p, lo, hi = boot_gap(k, f"kindblock_size_km{int(s)}_offset0")
            a = e1[(e1.task == k) & (e1.encoder == "tte") & (e1.split_size_km == s)].set_index("split_offset").score
            b = e1[(e1.task == k) & (e1.encoder == "satclip_l40") & (e1.split_size_km == s)].set_index("split_offset").score
            md.append(f"| {LABEL[k]} | {int(s)} km blocks | {fmt(k, p)} | [{fmt(k, lo)}, {fmt(k, hi)}] | {(a > b).sum()}/5 |")
            gap_rows.append(dict(task=k, size=s, gap=p, lo=lo, hi=hi,
                                 nn=g[(g.task == k) & (g.encoder == 'tte') & (g.split_size_km == s)].nn.iloc[0]))
    pd.DataFrame(gap_rows).to_csv(OUT / "gap_tte_vs_satclip.csv", index=False)
    md.append("")

    # ---------------- E1b sparse labels
    if sparse is not None:
        sg = sparse.groupby(["task", "encoder", "split_frac"]).agg(score=("score", "mean"), nn=("median_nn_km", "mean")).reset_index()
        md.append("## E1b: random split with training labels thinned (mean over 5 seeds)\n")
        for k in ORDER:
            fr = sorted(sg[sg.task == k].split_frac.unique(), reverse=True)
            md.append(f"### {LABEL[k]}\n")
            md.append("| | " + " | ".join(f"{100*f:g}% labels" for f in fr) + " |")
            md.append("|---|" + "---|" * len(fr))
            md.append("| median km to nearest label | " + " | ".join(f"{sg[(sg.task==k)&(sg.encoder=='tte')&(sg.split_frac==f)].nn.iloc[0]:.0f}" for f in fr) + " |")
            for enc in ["tte", "satclip_l40", "satclip_l10", "sh_l10", "coords"]:
                md.append(f"| {NAME[enc]} | " + " | ".join(fmt(k, sg[(sg.task==k)&(sg.encoder==enc)&(sg.split_frac==f)].score.iloc[0]) for f in fr) + " |")
            md.append("")

    # ---------------- distance vs region decomposition (blocks vs thinned labels at the same label distance)
    if sparse is not None:
        md.append("## Distance effect vs region effect\n")
        md.append("The drop from the random split to blocks has two parts. The **distance** part is what thinning labels on a random split "
                  "to the same median nearest-label distance costs (interpolated in log-distance from E1b). The **region** part is the "
                  "remainder: what holding out whole regions costs beyond being that far from labels. Blocks of 500 and 1000 km "
                  "(median distance ≈110 and ≈187 km) fall inside the E1b range (50–290 km).\n")
        md.append("| task | block | encoder | random | thinned labels at same distance | blocks | distance part | region part |")
        md.append("|---|---|---|---|---|---|---|---|")
        dec = []
        for k in ORDER:
            if k == "housing":
                continue
            for s in (500, 1000):
                for enc in ["tte", "satclip_l40", "satclip_l10", "coords"]:
                    blk = g[(g.task == k) & (g.encoder == enc) & (g.split_size_km == s)]
                    sp_ = sg[(sg.task == k) & (sg.encoder == enc)].sort_values("nn")
                    r0 = rnd[(rnd.task == k) & (rnd.encoder == enc)]
                    xs = np.log(np.r_[r0.nn.values, sp_.nn.values]); ys = np.r_[r0.score.values, sp_.score.values]
                    o = np.argsort(xs)
                    thin = float(np.interp(np.log(blk.nn.iloc[0]), xs[o], ys[o]))
                    b, r = float(blk.score.iloc[0]), float(r0.score.iloc[0])
                    dec.append(dict(task=k, block_km=s, encoder=enc, random=r, thinned=thin, blocks=b, distance_part=r - thin, region_part=thin - b))
                    md.append(f"| {LABEL[k]} | {s} km | {NAME[enc]} | {fmt(k, r)} | {fmt(k, thin)} | {fmt(k, b)} | {fmt(k, r - thin)} | {fmt(k, thin - b)} |")
        pd.DataFrame(dec).to_csv(OUT / "decomposition_distance_region.csv", index=False)
        md.append("")

    md += e3_sections(e0, e1, sys.modules[__name__])
    md += e2_sections(sys.modules[__name__])
    (OUT / "RESULTS_TABLES.md").write_text("\n".join(md))
    print("wrote outputs/RESULTS_TABLES.md")

    # ---------------- Figure 1: score vs distance to nearest label
    from matplotlib.ticker import FixedLocator, NullFormatter, NullLocator
    fig, axes = plt.subplots(2, 4, figsize=(13, 6.2))
    encs = ["tte", "satclip_l40", "satclip_l10", "coords"]  # SH L10 is in the tables; omitted here for scale
    for ax, k in zip(axes.flat, ORDER):
        style(ax)
        sc = 100 if TASKS[k] == "cls" else 1
        for enc in encs:
            r0 = rnd[(rnd.task == k) & (rnd.encoder == enc)]
            r = g[(g.task == k) & (g.encoder == enc)].sort_values("split_size_km")
            if k == "housing":
                r = r[r.split_size_km <= 100]  # 200-km blocks leave too few blocks per fold in California
            xs = np.maximum(np.r_[r0.nn.values, r.nn.values], 0.5)  # housing random split: 0 km (duplicate coords)
            ys = np.r_[r0.score.values, r.score.values] * sc
            lw = 2.2 if enc in ("tte", "satclip_l40", "coords") else 1.4
            ax.plot(xs, ys, "-o", color=COL[enc], lw=lw, ms=4.5, label=NAME[enc] + " (blocks)", zorder=3,
                    markeredgecolor="white", markeredgewidth=0.8)
            if sparse is not None:
                s_ = sg[(sg.task == k) & (sg.encoder == enc)].sort_values("split_frac", ascending=False)
                ax.plot(np.maximum(np.r_[r0.nn.values, s_.nn.values], 0.5), np.r_[r0.score.values, s_.score.values] * sc, "--",
                        color=COL[enc], lw=1.0, alpha=0.8, zorder=2)
        ax.set_xscale("log")
        ticks = [0.5, 2, 5, 10, 20, 50] if k == "housing" else [30, 50, 100, 200, 400]
        ax.xaxis.set_major_locator(FixedLocator(ticks))
        ax.set_xticklabels(["0" if t == 0.5 else f"{t:g}" for t in ticks])
        ax.xaxis.set_minor_locator(NullLocator())
        ax.xaxis.set_minor_formatter(NullFormatter())
        ax.set_title(LABEL[k], fontsize=10, color=INK, loc="left")
        if k in ("biome", "temperature"):
            ax.set_ylabel("score", fontsize=9, color=INK2)
    ax = axes.flat[-1]
    ax.axis("off")
    from matplotlib.lines import Line2D
    h = [Line2D([], [], color=COL[e], lw=2.2 if e in ("tte", "satclip_l40", "coords") else 1.4, marker="o", ms=4.5) for e in encs]
    h += [Line2D([], [], color=INK2, lw=1.4, marker="o", ms=4)]
    labs = [NAME[e] for e in encs] + ["solid: spatial blocks\n(leftmost point = random 80/20 split)"]
    if sparse is not None:
        h += [Line2D([], [], color=INK2, lw=1.0, ls="--")]
        labs += ["dashed: random split, training labels\nthinned to 30 / 10 / 3 / 1%"]
    ax.legend(h, labs, loc="center left", frameon=False, fontsize=8.5, labelcolor=INK)
    fig.supxlabel("median distance from a test point to its nearest training label (km, log scale)", fontsize=9, color=INK2)
    fig.suptitle("Frozen location encoders under random vs spatial-block evaluation (ridge probe, same protocol as TTE's eval_range.py)",
                 fontsize=11, color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(FIG / "fig1_score_vs_label_distance.png", dpi=200)
    print("wrote figures/fig1_score_vs_label_distance.png")

    # ---------------- Figure 2: TTE - SatCLIP gap vs block size with CIs
    gr = pd.DataFrame(gap_rows)
    fig, axes = plt.subplots(1, 7, figsize=(14, 2.9), sharey=False)
    for ax, k in zip(axes, ORDER):
        style(ax)
        sc = 100 if TASKS[k] == "cls" else 1
        r = gr[gr.task == k].sort_values("nn")
        if k == "housing":
            r = r[r["size"] <= 100]  # 200-km blocks: too few blocks per fold in California (see tables)
        x = np.arange(len(r))
        ax.axhline(0, color=INK2, lw=0.8)
        ax.errorbar(x, r.gap * sc, yerr=[(r.gap - r.lo) * sc, (r.hi - r.gap) * sc], fmt="o", color=COL["tte"],
                    ecolor=COL["tte"], elinewidth=1.4, capsize=0, ms=5, markeredgecolor="white")
        ax.set_xticks(x, ["rand"] + [(f"{int(s)//1000}k" if s >= 1000 else f"{int(s)}") for s in r["size"].iloc[1:]], fontsize=7.5)
        ax.set_title(LABEL[k].replace(" (", "\n("), fontsize=8.5, color=INK, loc="left")
    axes[0].set_ylabel("TTE − SatCLIP L40", fontsize=9, color=INK2)
    fig.supxlabel("split (block side in km)", fontsize=9, color=INK2)
    fig.tight_layout()
    fig.savefig(FIG / "fig2_gap_tte_minus_satclip.png", dpi=200)
    print("wrote figures/fig2_gap_tte_minus_satclip.png")


if __name__ == "__main__":
    main()
